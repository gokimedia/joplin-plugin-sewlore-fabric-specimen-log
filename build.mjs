import { build } from 'esbuild';
import { mkdir, readFile, writeFile, copyFile, readdir } from 'node:fs/promises';
import { create } from 'tar';
import { createHash } from 'node:crypto';
const manifest = JSON.parse(await readFile('src/manifest.json', 'utf8'));
const pkg = JSON.parse(await readFile('package.json', 'utf8'));
if (pkg.version !== manifest.version || !pkg.name.replace(/^@[^/]+\//, '').startsWith('joplin-plugin-') || !pkg.keywords.includes('joplin-plugin')) throw new Error('Invalid Joplin package metadata.');
await mkdir('dist', { recursive: true });
await mkdir('publish', { recursive: true });
await mkdir('qa/compiled', { recursive: true });
await build({ entryPoints: ['src/index.ts'], outfile: 'dist/index.js', bundle: true, platform: 'node', target: 'es2021', format: 'cjs', minify: false, alias: { api: './api' } });
await build({ entryPoints: ['src/core.ts'], outfile: 'qa/compiled/core.cjs', bundle: true, platform: 'node', target: 'es2021', format: 'cjs' });
await copyFile('src/manifest.json', 'dist/manifest.json');
await copyFile('LICENSE', 'dist/LICENSE');
await copyFile('THIRD-PARTY-NOTICES.md', 'dist/THIRD-PARTY-NOTICES.md');
const jpl = `publish/${manifest.id}.jpl`;
await create({ cwd: 'dist', file: jpl, portable: true, noMtime: true }, (await readdir('dist')).sort());
const sha = createHash('sha256').update(await readFile(jpl)).digest('hex');
await writeFile(`publish/${manifest.id}.json`, JSON.stringify({ ...manifest, _publish_hash: `sha256:${sha}`, _publish_commit: '' }, null, 2) + '\n');
console.log(JSON.stringify({ build: 'ok', jpl, sha256: sha, nativeAppInstalledTested: false }));
